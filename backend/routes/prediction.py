"""
backend/routes/prediction.py
Flask Blueprint for water quality prediction endpoints,
model performance metrics, prediction history, and system health checks.
"""

import os
import joblib
from flask import Blueprint, jsonify, request

from ml.water_quality import predict_water_quality, FEATURE_COLUMNS
from database.db import log_prediction, get_recent_predictions

prediction_bp = Blueprint("prediction_bp", __name__)

_MODEL_PATH = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "models", "water_quality_model.joblib")
)

# Reference guideline ranges for water quality parameters
_SAFE_RANGES = {
    "ph":               (6.5, 8.5,  "WHO guideline: 6.5–8.5"),
    "Hardness":         (0,   300,   "Soft to moderately hard: 0–300 mg/L"),
    "Solids":           (0,   500,   "WHO guideline TDS: < 500 mg/L"),
    "Chloramines":      (0,   4.0,   "EPA maximum disinfectant residual: 4 mg/L"),
    "Sulfate":          (0,   250,   "WHO guideline: < 250 mg/L"),
    "Conductivity":     (0,   400,   "Typical potable conductivity: < 400 μS/cm"),
    "Organic_carbon":   (0,   2.0,   "EPA guideline TOC: < 2 mg/L"),
    "Trihalomethanes":  (0,   80,    "WHO guideline THMs: < 80 μg/L"),
    "Turbidity":        (0,   4.0,   "WHO guideline: < 4 NTU"),
}


def _get_region_info(region_name):
    """Retrieve approximate water accessibility indicators for the specified region."""
    region_map = {
        "africa":   {"avg_basic_water_access_pct": 47.5, "note": "Sub-Saharan Africa experiences acute infrastructure bottlenecks."},
        "asia":     {"avg_basic_water_access_pct": 79.6, "note": "Significant variability between East Asia and South/Central Asia."},
        "europe":   {"avg_basic_water_access_pct": 97.2, "note": "Universal safely managed water access and strict EU standards."},
        "americas": {"avg_basic_water_access_pct": 82.4, "note": "Near-universal coverage in North America; moderate coverage in Latin America."},
        "oceania":  {"avg_basic_water_access_pct": 68.8, "note": "Pacific small-island nations face freshwater lens salinity challenges."},
    }
    if region_name:
        key = region_name.strip().lower()
        for k, v in region_map.items():
            if k in key or key in k:
                return v
        return {"note": f"Survey indicators recorded for '{region_name}'."}
    return None


@prediction_bp.route("/api/predict-water-quality", methods=["POST"])
def predict():
    """
    POST /api/predict-water-quality
    Predicts water potability given physicochemical indicators,
    calculates flags for non-compliant parameters, logs prediction in SQLite.
    """
    try:
        body = request.get_json(force=True, silent=True) or {}
        region = body.pop("region", None)

        missing = [col for col in FEATURE_COLUMNS if col not in body]
        if missing:
            return jsonify({
                "error": f"Missing required parameters: {missing}",
                "required_fields": FEATURE_COLUMNS,
            }), 400

        input_dict = {}
        for col in FEATURE_COLUMNS:
            try:
                input_dict[col] = float(body[col])
            except (TypeError, ValueError):
                return jsonify({"error": f"Parameter '{col}' must be a valid number."}), 400

        if not os.path.exists(_MODEL_PATH):
            return jsonify({
                "error": "Water quality model is not available. Please wait for model initialization."
            }), 503

        result = predict_water_quality(_MODEL_PATH, input_dict)
        prediction = result["prediction"]
        prediction_label = "Potable" if prediction == 1 else "Not Potable"
        confidence = result["confidence"]

        # Guideline verification
        flags = []
        for feat, (lo, hi, note) in _SAFE_RANGES.items():
            val = input_dict.get(feat)
            if val is not None and not (lo <= val <= hi):
                flags.append({
                    "parameter": feat,
                    "value": val,
                    "guideline": note,
                    "status": "Exceeds guideline" if val > hi else "Below recommended minimum"
                })

        # Log into SQLite database
        log_prediction(input_dict, prediction, prediction_label, confidence, region)

        response = {
            "prediction": prediction,
            "prediction_label": prediction_label,
            "confidence": confidence,
            "feature_importances": result["feature_importances"],
            "parameter_flags": flags,
            "disclaimer": (
                "Educational Estimate: This prediction is generated by a Scikit-Learn Random Forest "
                "trained on historical survey indicators. It does NOT substitute certified laboratory testing. "
                "Drinking water safety must conform to local regulatory standards."
            ),
        }

        if region:
            reg_info = _get_region_info(region)
            if reg_info:
                response["region_info"] = reg_info

        return jsonify(response)

    except Exception as e:
        return jsonify({"error": str(e)}), 500


@prediction_bp.route("/api/prediction-history", methods=["GET"])
def prediction_history():
    """
    GET /api/prediction-history
    Returns the most recent predictions recorded in SQLite.
    """
    try:
        limit = int(request.args.get("limit", 10))
        history = get_recent_predictions(limit=limit)
        return jsonify({"history": history, "count": len(history)})
    except Exception as e:
        return jsonify({"error": str(e)}), 500


@prediction_bp.route("/api/water-quality-metrics", methods=["GET"])
def model_metrics():
    """
    GET /api/water-quality-metrics
    Returns actual trained model metrics (accuracy, precision, recall, confusion matrix).
    """
    try:
        if not os.path.exists(_MODEL_PATH):
            return jsonify({"error": "Model bundle not found on disk."}), 404

        bundle = joblib.load(_MODEL_PATH)
        metrics = bundle.get("metrics", {})
        return jsonify({"metrics": metrics})
    except Exception as e:
        return jsonify({"error": str(e)}), 500


@prediction_bp.route("/api/health", methods=["GET"])
def health_check():
    """
    GET /api/health
    Returns operational status of backend, database, and models.
    """
    try:
        model_exists = os.path.exists(_MODEL_PATH)
        data_path = os.path.abspath(
            os.path.join(os.path.dirname(__file__), "..", "data", "wash_dataset.csv")
        )
        dataset_exists = os.path.exists(data_path)

        return jsonify({
            "status": "ok",
            "model_trained": model_exists,
            "dataset_loaded": dataset_exists,
            "version": "1.0.0"
        })
    except Exception as e:
        return jsonify({"error": str(e)}), 500
